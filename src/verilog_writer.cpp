namespace {

std::string joined(const std::vector<std::string>& operands, const std::string& op) {
    std::string text;
    for (size_t i = 0; i < operands.size(); ++i) text += (i ? " " + op + " " : "") + operands[i];
    return text;
}

bool simpleIdentifier(const std::string& s) {
    if (s.empty() || !(std::isalpha(static_cast<unsigned char>(s[0])) || s[0] == '_')) return false;
    for (char c : s) {
        if (!(std::isalnum(static_cast<unsigned char>(c)) || c == '_' || c == '$')) return false;
    }
    return true;
}

// "u_core.acc[3]" -> "\u_core.acc [3]": hierarchical names become escaped identifiers,
// keeping the bit / word selects outside the escaped part
std::string verilogRef(const std::string& name) {
    size_t b = name.find('[');
    std::string base = name.substr(0, b), rest = b == std::string::npos ? "" : name.substr(b);
    return simpleIdentifier(base) ? name : "\\" + base + " " + rest;
}

} // namespace

void writeVerilog(std::ostream& out, const Design& design) {
    // Ports that are flip-flop outputs are written as "output reg"
    std::set<std::string> seq_ports;
    for (const auto& d : design.reg_decls) {
        if (d.is_port) seq_ports.insert(d.name);
    }

    out << "// Gate-level netlist generated by ASIC_backend\n";
    out << "module " << design.name << " (\n";
    for (size_t i = 0; i < design.ports.size(); ++i) {
        const PortInfo& port = design.ports[i];
        out << "    " << (port.is_input ? "input  " : seq_ports.count(port.name) ? "output reg " : "output ");
        if (port.is_vector) out << "[" << port.msb << ":" << port.lsb << "] ";
        out << port.name << (i + 1 < design.ports.size() ? "," : "") << "\n";
    }
    out << ");\n";
    for (const auto& d : design.reg_decls) {
        if (d.is_port) continue;
        out << "    reg ";
        if (d.is_vector) out << "[" << d.msb << ":" << d.lsb << "] ";
        out << verilogRef(d.name);
        if (d.is_memory) out << " [" << d.first << ":" << d.last << "]";
        out << ";\n";
    }

    // Ports, registers and constants keep their own names; every gate becomes a wire named after its id
    std::unordered_map<const GateNode*, std::string> names;
    for (const auto& node : topologicalOrder(design.forest)) {
        std::vector<std::string> in;
        for (const auto& fanin : node->inputs) in.push_back(names.at(fanin.get()));

        std::string expr;
        switch (node->type) {
        case GateType::INPUT:
        case GateType::OUTPUT: names[node.get()] = verilogRef(node->name); continue;
        case GateType::CONST0: names[node.get()] = "1'b0"; continue;
        case GateType::CONST1: names[node.get()] = "1'b1"; continue;
        case GateType::ASSIGN:
        case GateType::BUF:    names[node.get()] = in.at(0); continue;   // no logic: alias the driver
        case GateType::NOT:    expr = "~" + in.at(0); break;
        case GateType::NAND:   expr = "~(" + joined(in, "&") + ")"; break;
        case GateType::AND:    expr = joined(in, "&"); break;
        case GateType::NOR:    expr = "~(" + joined(in, "|") + ")"; break;
        case GateType::OR:     expr = joined(in, "|"); break;
        case GateType::XNOR:   expr = "~(" + joined(in, "^") + ")"; break;
        case GateType::XOR:    expr = joined(in, "^"); break;
        default:
            throw std::runtime_error("cannot write " + gateTypeName(node->type) + " gates yet");
        }
        std::string wire = instanceName(*node);
        names[node.get()] = wire;
        out << "    wire " << wire << " = " << expr << ";\n";
    }

    std::unordered_map<std::string, std::string> next_of;   // register -> its D expression
    std::unordered_map<std::string, std::string> macro_in;  // macro input root -> its driver
    for (const auto& root : design.forest) {
        const std::string& driver = names.at(root->inputs.at(0).get());
        if (isMacroInputName(root->name)) {
            macro_in[root->name] = driver;
        } else if (isNextStateName(root->name)) {
            next_of[root->name.substr(0, root->name.size() - 5)] = driver;
        } else if (driver != verilogRef(root->name)) {   // an output reg is its own driver
            out << "    assign " << verilogRef(root->name) << " = " << driver << ";\n";
        }
    }

    // One always block per clock / reset combination
    std::map<std::tuple<std::string, bool, std::string, bool>, std::vector<const RegisterBit*>> domains;
    for (const auto& r : design.registers) domains[{r.clock, r.negedge, r.reset, r.reset_active_low}].push_back(&r);
    for (const auto& [key, regs] : domains) {
        const auto& [clock, negedge, reset, active_low] = key;
        out << "    always @(" << (negedge ? "negedge " : "posedge ") << clock;
        if (!reset.empty()) out << " or " << (active_low ? "negedge " : "posedge ") << reset;
        out << ")";
        if (!reset.empty()) {
            out << "\n        if (" << (active_low ? "!" : "") << reset << ") begin\n";
            for (const RegisterBit* r : regs) out << "            " << verilogRef(r->name) << " <= 1'b" << (r->reset_value ? 1 : 0) << ";\n";
            out << "        end else begin\n";
        } else {
            out << " begin\n";
        }
        for (const RegisterBit* r : regs) out << "            " << verilogRef(r->name) << " <= " << next_of.at(r->name) << ";\n";
        out << (reset.empty() ? "    end\n" : "        end\n");
    }
    // Hard macros: bus pins are connected with concatenations, most significant bit first
    for (const auto& m : design.macros) {
        struct Bus { std::map<int, std::string, std::greater<int>> bits; std::string scalar; bool is_bus = false; };
        std::map<std::string, Bus> pins;   // by pin / bus name
        std::vector<std::string> order;
        auto add = [&](const std::string& pin, const std::string& net) {
            size_t b = pin.find('[');
            std::string base = pin.substr(0, b);
            if (!pins.count(base)) order.push_back(base);
            Bus& bus = pins[base];
            if (b == std::string::npos) bus.scalar = net;
            else {
                bus.is_bus = true;
                bus.bits[std::stoi(pin.substr(b + 1))] = net;
            }
        };
        std::map<std::string, std::pair<int, int>> out_buses;
        for (const auto& [pin, root] : m.inputs) add(pin, macro_in.at(root));
        for (const auto& [pin, q] : m.outputs) {
            add(pin, verilogRef(q));
            size_t b = q.rfind('[');   // declare the nets the outputs drive, by their own names
            if (b == std::string::npos || q.back() != ']') {
                out << "    wire " << verilogRef(q) << ";\n";
            } else {
                int bit = std::stoi(q.substr(b + 1));
                std::string base = q.substr(0, b);
                auto& range = out_buses.emplace(base, std::make_pair(bit, bit)).first->second;
                range.first = std::max(range.first, bit);
                range.second = std::min(range.second, bit);
            }
        }
        for (const auto& [base, range] : out_buses) {
            out << "    wire [" << range.first << ":" << range.second << "] " << verilogRef(base) << ";\n";
        }
        out << "    " << m.cell << " " << verilogRef(m.name) << " (";
        for (size_t k = 0; k < order.size(); ++k) {
            const Bus& bus = pins.at(order[k]);
            out << (k ? "," : "") << "\n        ." << order[k] << "(";
            if (!bus.is_bus) {
                out << bus.scalar;
            } else {
                out << "{";
                bool first = true;
                for (const auto& [bit, net] : bus.bits) {
                    out << (first ? "" : ", ") << net;
                    first = false;
                }
                out << "}";
            }
            out << ")";
        }
        out << "\n    );\n";
    }
    out << "endmodule\n";
}
